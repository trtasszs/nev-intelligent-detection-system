def _score(entry, text):
    """关键词命中打分：长关键词权重更高。"""
    score = 0
    for kw in entry["keywords"]:
        if kw in text:
            score += len(kw) + 1
    return score


def match(text):
    """按关键词匹配最合适的知识条目，返回 (entry, score)。"""
    text = (text or "").lower()
    best, best_score = None, 0
    for entry in KNOWLEDGE:
        s = _score(entry, text)
        if s > best_score:
            best, best_score = entry, s
    if best is None:
        return FALLBACK, 0
    return best, best_score


